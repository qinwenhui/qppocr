//! 内部 SHA-256。零依赖（不引 `sha2`——校验是 `ModelSource` 的核心职责，
//! 不值得为它带一个传递依赖树）。
//!
//! 标准实现：FIPS 180-4。只用于模型文件校验，性能不敏感
//!（76 MB 的 medium det ~200 ms，构造引擎时一次）。

